// Renders one role definition into the agent format of each supported tool.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const MARKER = 'Generated by abraham-harness. Do not edit.';
const MARKER_LINES = new Set([`<!-- ${MARKER} -->`, `# ${MARKER}`]);
const READ_ONLY_TOOLS = 'Read, Glob, Grep, Bash, Skill';
const CLAUDE_TOOLS = {
  write: null,
  spec: `${READ_ONLY_TOOLS}, Write, Edit`,
  'read-only': READ_ONLY_TOOLS,
};
const OPENCODE_PERMISSION = {
  write: '',
  spec: 'permission:\n  edit:\n    "*": deny\n    ".agents/plans/**": allow\n',
  'read-only': 'permission:\n  edit: deny\n',
};

export const ACCESS_LEVELS = Object.keys(CLAUDE_TOOLS);

export function loadRoles(dir) {
  const contract = readFileSync(join(dir, 'shared/review-contract.md'), 'utf8').trim();
  return readdirSync(dir)
    .filter((file) => file.endsWith('.md'))
    .sort()
    .map((file) => parseRole(readFileSync(join(dir, file), 'utf8'), contract));
}

function parseRole(text, contract) {
  const [, head, body] = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  const fields = Object.fromEntries(
    head.split('\n').map((line) => {
      const separator = line.indexOf(':');
      return [line.slice(0, separator), line.slice(separator + 1).trim().replace(/^"|"$/g, '')];
    }),
  );
  const instructions = body.trim().replaceAll('{{ROLE}}', fields.name).replace('{{REVIEW_CONTRACT}}', () => contract.replaceAll('{{ROLE}}', fields.name));
  const skills = fields.skills ? fields.skills.split(',').map((skill) => skill.trim()) : [];
  return { name: fields.name, description: fields.description, access: fields.access, skills, instructions };
}

// Only Claude Code can preload skills, so the other tools receive the instruction in the prompt.
function withLoadInstruction(role) {
  if (role.skills.length === 0) return role.instructions;
  const names = role.skills.map((skill) => `\`${skill}\``).join(', ');
  return `Load these skills before you work: ${names}.\n\n${role.instructions}`;
}

function renderClaude(role) {
  const tools = CLAUDE_TOOLS[role.access];
  const lines = ['---', `name: ${role.name}`, `description: ${JSON.stringify(role.description)}`];
  if (tools) lines.push(`tools: ${tools}`);
  if (role.skills.length > 0) lines.push('skills:', ...role.skills.map((skill) => `  - ${skill}`));
  lines.push('---', '', `<!-- ${MARKER} -->`, '', role.instructions, '');
  return lines.join('\n');
}

function renderOpenCode(role) {
  return `---
description: ${JSON.stringify(role.description)}
mode: subagent
${OPENCODE_PERMISSION[role.access]}---

<!-- ${MARKER} -->

${withLoadInstruction(role)}
`;
}

// JSON string escapes are valid in a TOML basic string.
function renderCodex(role) {
  return `# ${MARKER}
name = ${JSON.stringify(role.name)}
description = ${JSON.stringify(role.description)}
developer_instructions = ${JSON.stringify(withLoadInstruction(role))}
`;
}

function targets(isGlobal) {
  return [
    { dir: '.claude/agents', ext: 'md', render: renderClaude },
    { dir: isGlobal ? '.config/opencode/agents' : '.opencode/agents', ext: 'md', render: renderOpenCode },
    { dir: '.codex/agents', ext: 'toml', render: renderCodex },
  ];
}

// A prose mention of the marker must not make a hand-written file replaceable.
function isGenerated(path) {
  return readFileSync(path, 'utf8').split('\n').some((line) => MARKER_LINES.has(line));
}

export function installAgents(roles, { base, isGlobal }) {
  const written = [];
  const skipped = [];
  for (const { dir, ext, render } of targets(isGlobal)) {
    for (const role of roles) {
      const relativePath = `${dir}/${role.name}.${ext}`;
      const path = join(base, relativePath);
      if (existsSync(path) && !isGenerated(path)) {
        skipped.push(relativePath);
        continue;
      }
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, render(role));
      written.push(relativePath);
    }
  }
  return { written, skipped };
}

// Updates only what is already installed, so an update never adds agents to a project.
export function refreshAgents(roles, scopes) {
  let refreshed = 0;
  for (const { base, isGlobal } of scopes) {
    for (const { dir, ext, render } of targets(isGlobal)) {
      for (const role of roles) {
        const path = join(base, `${dir}/${role.name}.${ext}`);
        if (!existsSync(path) || !isGenerated(path)) continue;
        writeFileSync(path, render(role));
        refreshed += 1;
      }
    }
  }
  return refreshed;
}
